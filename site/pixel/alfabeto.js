export const LARGHEZZA = 5;
export const ALTEZZA = 7;

/* dal disegno alle colonne di bit: colonna[x], bit y acceso = pixel */
export const ALFABETO = {};
for (const [ch, arte] of Object.entries(DISEGNI)) {
  const righe = arte.split('/');
  const col = new Uint8Array(LARGHEZZA);
  for (let y = 0; y < ALTEZZA; y++)
    for (let x = 0; x < LARGHEZZA; x++)
      if (righe[y][x] === '#') col[x] |= 1 << y;
  ALFABETO[ch] = col;
}

/* le lettere accentate minuscole ricadono sulla maiuscola accentata,
   il resto sulla maiuscola semplice: l'alfabeto è tutto in capitali */
export function glifo(ch) {
  return ALFABETO[ch]
      || ALFABETO[ch.toUpperCase()]
      || ALFABETO[ch.toUpperCase().normalize('NFD').replace(/[̀-ͯ]/g, '')]
      || ALFABETO['?'];
}
